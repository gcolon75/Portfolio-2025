// Builds the VI system prompt from the site's data files before every wrangler dev/deploy.
// The site's data imports images and PDFs, which the Worker cannot bundle, so esbuild stubs them out here.
import { build } from 'esbuild';
import { mkdir, writeFile, rm } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
const root = path.resolve(here, '..');
const assetExts = ['.png', '.jpg', '.jpeg', '.webp', '.gif', '.svg', '.pdf', '.docx', '.PNG', '.JPG', '.JPEG'];

const tmp = path.join(root, '.wrangler', 'tmp-knowledge.mjs');
await mkdir(path.dirname(tmp), { recursive: true });
await build({
  entryPoints: [path.resolve(root, '../src/vi/knowledge.js')],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  outfile: tmp,
  loader: Object.fromEntries(assetExts.map((e) => [e, 'empty'])),
  define: { 'process.env.PUBLIC_URL': '""' },
  logLevel: 'error'
});

const { buildSystemPrompt } = await import(pathToFileURL(tmp).href);
const prompt = buildSystemPrompt();
await rm(tmp);

const outDir = path.join(root, 'src', 'generated');
await mkdir(outDir, { recursive: true });
await writeFile(
  path.join(outDir, 'system-prompt.js'),
  `// Generated by scripts/build-prompt.mjs. Do not edit; edit src/data in the site instead.\nexport const SYSTEM_PROMPT = ${JSON.stringify(prompt)};\n`
);
console.log(`VI system prompt built: ${prompt.length} chars`);
